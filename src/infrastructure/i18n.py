# Process-wide default, overridable at runtime (CLI flag, wizard choice, UI_LANG env var).
_active_language = normalize_language(os.environ.get("UI_LANG", DEFAULT_LANGUAGE))


def set_language(language: Any) -> str:
    """Set the process-wide default language and return the resolved code."""
    global _active_language
    _active_language = normalize_language(language)
    return _active_language


def get_language() -> str:
    """Return the current process-wide default language code."""
    return _active_language


def language_name(code: Any) -> str:
    """Return the human-readable name of a language code."""
    return LANGUAGE_NAMES.get(normalize_language(code), LANGUAGE_NAMES[DEFAULT_LANGUAGE])


def t(key: str, lang: Any = None, **kwargs: Any) -> str:
    """Resolve a message key in the given language, formatting any placeholders.

    Falls back to English, then to the raw key, so a missing translation never raises.
    """
    code = normalize_language(lang) if lang is not None else _active_language
    template = _catalog.get(code, {}).get(key)
    if template is None:
        template = _catalog[DEFAULT_LANGUAGE].get(key, key)
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template
