"""User-facing message catalogue with runtime language selection (English / Indonesian).

Every string a human reads - Telegram replies, the setup wizard, CLI diagnostics - is
resolved through :func:`t`. English is the default so a first-time user of any origin can
follow the product; Indonesian is available via ``UI_LANG=id``, the ``--lang`` flag, or the
Telegram ``/lang`` command (persisted per user).

A missing key returns the key itself instead of raising, so a translation gap degrades to a
readable token rather than a crashed handler.
"""

from __future__ import annotations

import os
from typing import Any, Dict, List

DEFAULT_LANGUAGE = "en"

# Display name per language code, used by `/lang` and the wizard menu.
LANGUAGE_NAMES: Dict[str, str] = {
    "en": "English",
    "id": "Bahasa Indonesia",
}

# Aliases users may type (e.g. `/lang indo`).
_LANGUAGE_ALIASES: Dict[str, str] = {
    "en": "en",
    "eng": "en",
    "english": "en",
    "inggris": "en",
    "id": "id",
    "ind": "id",
    "indonesia": "id",
    "indonesian": "id",
    "indo": "id",
    "bahasa": "id",
}


def normalize_language(value: Any) -> str:
    """Return a supported language code, falling back to the default for unknown input."""
    cleaned = str(value or "").strip().lower()
    return _LANGUAGE_ALIASES.get(cleaned, DEFAULT_LANGUAGE)


def is_supported_language(value: Any) -> bool:
    """Whether `value` names a language we ship (by code, name, or alias)."""
    return str(value or "").strip().lower() in _LANGUAGE_ALIASES


def available_languages() -> List[str]:
    """Return the supported language codes in menu order."""
    return list(LANGUAGE_NAMES.keys())


